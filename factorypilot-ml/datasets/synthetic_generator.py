def generate_synthetic_incidents(num_samples: int = 400, seed: int = DEFAULT_RANDOM_SEED) -> pd.DataFrame:
    """Generate realistic synthetic incident records for classification & evaluation."""
    rng = random.Random(seed)
    records = []
    base_date = datetime(2025, 1, 1)

    for i in range(num_samples):
        cat = rng.choice(INCIDENT_CATEGORIES)
        template = rng.choice(INCIDENT_TEMPLATES[cat])
        machine = rng.choice(MACHINES)
        area = rng.choice(DEPARTMENTS)
        site = rng.choice(SITES)
        description = template.format(machine=machine, area=area)

        # Realistic severity distribution conditional on category
        if cat in ["Chemical Exposure", "Electrical Hazard", "Thermal / Burn"]:
            severity = rng.choices(["Medium", "High", "Critical"], weights=[0.4, 0.45, 0.15])[0]
        elif cat in ["Slip / Trip / Fall", "Ergonomic / Repetitive Strain"]:
            severity = rng.choices(["Low", "Medium", "High"], weights=[0.4, 0.45, 0.15])[0]
        elif cat == "Machinery / Mechanical":
            severity = rng.choices(["Low", "Medium", "High", "Critical"], weights=[0.2, 0.35, 0.35, 0.1])[0]
        else:
            severity = rng.choices(["Low", "Medium", "High"], weights=[0.6, 0.3, 0.1])[0]

        event_date = base_date + timedelta(days=rng.randint(0, 365), hours=rng.randint(0, 23))
        lost_work_days = 0 if severity == "Low" else (rng.randint(0, 5) if severity == "Medium" else rng.randint(6, 45))
        osha_recordable = 1 if severity in ["Medium", "High", "Critical"] and rng.random() > 0.3 else 0

        records.append({
            "incident_id": f"INC-2025-{1000 + i}",
            "site": site,
            "department": area,
            "machine_code": machine,
            "timestamp": event_date.strftime("%Y-%m-%d %H:%M:%S"),
            "category": cat,
            "severity": severity,
            "description": description,
            "lost_work_days": lost_work_days,
            "osha_recordable": osha_recordable,
            "sample_dataset_note": "BENCHMARK SYNTHETIC DATA FOR PIPELINE VALIDATION"
        })

    return pd.DataFrame(records)


def generate_synthetic_near_misses(num_samples: int = 500, seed: int = DEFAULT_RANDOM_SEED) -> pd.DataFrame:
    """Generate realistic synthetic near-miss records."""
    rng = random.Random(seed)
    records = []
    base_date = datetime(2025, 1, 1)

    domain_keys = list(NEAR_MISS_TEMPLATES.keys())

    for i in range(num_samples):
        domain = rng.choice(domain_keys)
        template, root_cause, default_sev = rng.choice(NEAR_MISS_TEMPLATES[domain])
        machine = rng.choice(MACHINES)
        area = rng.choice(DEPARTMENTS)
        site = rng.choice(SITES)
        description = template.format(machine=machine, area=area)

        # 85% pure near misses, 15% minor actual incident comparisons to train distinction
        is_near_miss = 1 if rng.random() < 0.88 else 0
        potential_severity = default_sev if rng.random() > 0.2 else rng.choice(["Minor", "Moderate", "Severe", "Catastrophic"])
        reported_within_hours = rng.choice([0.5, 1.0, 2.0, 4.0, 8.0, 24.0, 48.0])

        records.append({
            "report_id": f"NM-2025-{2000 + i}",
            "site": site,
            "department": area,
            "machine_code": machine,
            "timestamp": (base_date + timedelta(days=rng.randint(0, 365), hours=rng.randint(0, 23))).strftime("%Y-%m-%d %H:%M:%S"),
            "is_near_miss": is_near_miss,
            "root_cause_domain": root_cause,
            "potential_severity": potential_severity,
            "description": description,
            "reported_within_hours": reported_within_hours,
            "action_required": 1 if potential_severity in ["Severe", "Catastrophic"] else (1 if rng.random() > 0.4 else 0),
            "sample_dataset_note": "BENCHMARK SYNTHETIC DATA FOR PIPELINE VALIDATION"
        })

    return pd.DataFrame(records)


