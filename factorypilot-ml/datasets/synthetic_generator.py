def generate_synthetic_corrective_actions(num_samples: int = 500, seed: int = DEFAULT_RANDOM_SEED) -> pd.DataFrame:
    """Records of assigned safety corrective actions with outcomes (completed on time vs overdue)."""
    rng = random.Random(seed)
    records = []
    assignees = ["EHS-Officer-Smith", "Maintenance-Lead-Chen", "Facility-Tech-Miller", "Ops-Supervisor-Patel", "Safety-Rep-Alvarez"]

    for i in range(num_samples):
        cat = rng.choice(INCIDENT_CATEGORIES)
        site = rng.choice(SITES)
        dept = rng.choice(DEPARTMENTS)
        assignee = rng.choice(assignees)
        priority = rng.choices(["Low", "Medium", "High", "Critical"], weights=[0.25, 0.45, 0.2, 0.1])[0]

        # Features influencing overdue probability
        days_allocated = rng.choice([3, 7, 14, 30, 45, 60])
        assignee_active_tickets = rng.randint(1, 15)
        capex_required_usd = rng.choice([0, 0, 500, 2500, 8000, 25000])
        vendor_involved = 1 if capex_required_usd > 1000 or rng.random() < 0.25 else 0
        action_complexity = rng.choices(["Simple", "Moderate", "Complex"], weights=[0.4, 0.45, 0.15])[0]

        # Latent risk score for overdue
        overdue_score = (
            (0.3 if priority == "Critical" else 0.1) +
            (assignee_active_tickets * 0.05) +
            (0.25 if vendor_involved else 0.0) +
            (0.3 if action_complexity == "Complex" else (0.1 if action_complexity == "Moderate" else 0.0)) -
            (days_allocated * 0.005)
        )
        is_overdue = 1 if (overdue_score + rng.gauss(0, 0.2)) > 0.45 else 0
        actual_days_taken = int(days_allocated + (rng.randint(3, 35) if is_overdue else -rng.randint(0, max(0, days_allocated - 1))))
        days_delay = max(0, actual_days_taken - days_allocated) if is_overdue else 0

        action_title = f"Remediate {cat.lower()} issue on {rng.choice(MACHINES)} in {dept}"

        records.append({
            "action_id": f"CAPA-{4000 + i}",
            "action_title": action_title,
            "site": site,
            "department": dept,
            "priority": priority,
            "action_category": cat,
            "action_complexity": action_complexity,
            "assignee": assignee,
            "assignee_active_tickets": assignee_active_tickets,
            "days_allocated": days_allocated,
            "capex_required_usd": capex_required_usd,
            "vendor_involved": vendor_involved,
            "actual_days_taken": actual_days_taken,
            "is_overdue": is_overdue,
            "days_delay": days_delay,
            "sample_dataset_note": "BENCHMARK SYNTHETIC DATA FOR PIPELINE VALIDATION"
        })

    return pd.DataFrame(records)


def generate_synthetic_site_safety_metrics(num_days: int = 180, seed: int = DEFAULT_RANDOM_SEED) -> pd.DataFrame:
    """Daily safety indicators per site for safety risk scoring and time-series trend analysis."""
    rng = random.Random(seed)
    records = []
    start_date = datetime(2025, 1, 1)

    site_baselines = {
        "Site-Detroit": {"risk_base": 32.0, "near_miss_rate": 1.8, "incident_prob": 0.08},
        "Site-Munich": {"risk_base": 18.0, "near_miss_rate": 2.5, "incident_prob": 0.03},
        "Site-Singapore": {"risk_base": 22.0, "near_miss_rate": 2.2, "incident_prob": 0.04},
        "Site-Austin": {"risk_base": 42.0, "near_miss_rate": 1.2, "incident_prob": 0.12},
        "Site-Yokohama": {"risk_base": 15.0, "near_miss_rate": 3.0, "incident_prob": 0.02}
    }

    for day_idx in range(num_days):
        current_date = start_date + timedelta(days=day_idx)
        for site, baseline in site_baselines.items():
            # Trend component (Austin improving slightly, Detroit has a seasonal bump)
            trend_effect = -0.05 * day_idx if site == "Site-Austin" else (3.0 * (1.0 if 60 <= day_idx <= 90 else 0.0))
            noise = rng.gauss(0, 2.5)
            
            near_misses = max(0, int(rng.poisson(baseline["near_miss_rate"]) if hasattr(rng, "poisson") else rng.randint(0, 4)))
            incidents = 1 if rng.random() < baseline["incident_prob"] else 0
            open_overdue_actions = max(0, int(rng.gauss(3.0 if site in ["Site-Detroit", "Site-Austin"] else 1.0, 1.2)))
            vibration_anomaly_idx = max(0.0, rng.gauss(1.1 if site == "Site-Detroit" else 0.8, 0.25))
            temp_anomaly_idx = max(0.0, rng.gauss(1.0, 0.2))
            training_compliance_pct = min(100.0, max(65.0, 94.0 - (0.15 * open_overdue_actions * 10) + rng.gauss(0, 3.0)))

            calculated_risk = max(5.0, min(95.0,
                baseline["risk_base"] + trend_effect + (incidents * 15.0) +
                (open_overdue_actions * 4.0) + ((100.0 - training_compliance_pct) * 0.3) +
                (vibration_anomaly_idx * 5.0) + noise
            ))

            if calculated_risk < 25:
                risk_tier = "LOW"
            elif calculated_risk < 50:
                risk_tier = "MEDIUM"
            elif calculated_risk < 75:
                risk_tier = "HIGH"
            else:
                risk_tier = "CRITICAL"

            records.append({
                "date": current_date.strftime("%Y-%m-%d"),
                "site": site,
                "daily_near_misses": near_misses,
                "daily_incidents": incidents,
                "open_overdue_actions": open_overdue_actions,
                "vibration_anomaly_index": round(vibration_anomaly_idx, 3),
                "temperature_anomaly_index": round(temp_anomaly_idx, 3),
                "training_compliance_pct": round(training_compliance_pct, 1),
                "safety_risk_score": round(calculated_risk, 2),
                "risk_tier": risk_tier,
                "sample_dataset_note": "BENCHMARK SYNTHETIC DATA FOR PIPELINE VALIDATION"
            })

    return pd.DataFrame(records)


def export_all_benchmark_datasets(output_dir: str) -> Dict[str, str]:
    """Export all generated benchmark datasets to CSV files inside output_dir."""
    import os
    os.makedirs(output_dir, exist_ok=True)

    files = {}
    incidents_df = generate_synthetic_incidents()
    inc_path = os.path.join(output_dir, "incident_reports_sample.csv")
    incidents_df.to_csv(inc_path, index=False)
    files["incidents"] = inc_path

    near_miss_df = generate_synthetic_near_misses()
    nm_path = os.path.join(output_dir, "near_miss_reports_sample.csv")
    near_miss_df.to_csv(nm_path, index=False)
    files["near_misses"] = nm_path

    hazards_df = generate_synthetic_hazards_catalog()
    haz_path = os.path.join(output_dir, "hazard_reports_sample.csv")
    hazards_df.to_csv(haz_path, index=False)
    files["hazards"] = haz_path

    actions_df = generate_synthetic_corrective_actions()
    act_path = os.path.join(output_dir, "corrective_actions_sample.csv")
    actions_df.to_csv(act_path, index=False)
    files["corrective_actions"] = act_path

    metrics_df = generate_synthetic_site_safety_metrics()
    met_path = os.path.join(output_dir, "site_safety_metrics_sample.csv")
    metrics_df.to_csv(met_path, index=False)
    files["site_metrics"] = met_path

    return files


